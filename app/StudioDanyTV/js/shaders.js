/* shaders.js — GLSL ES 1.00 sources (valid on WebGL2 and WebGL1).

   Two passes share one prelude (uniforms, noise, light state):

   SKY  -> rendered into a texture every N frames (the sky changes slowly). Time-of-day gradient,
           sun/moon disc with glow, stars with twinkle, Milky Way band, perspective fbm clouds.
   MAIN -> rendered every frame. Above the horizon it just samples the sky texture; the sea is
           computed per frame (layered waves, Caribbean palette, glint path under the light,
           foam at a wavy shore line) and reflects the real sky color sampled just above the horizon.

   Light model: `df` = fraction of daytime elapsed (0 at sunrise, 1 at sunset), `nf` = fraction of
   the night. Light elevation `elev` = sin(pi*df) by day, -sin(pi*nf) by night, so it crosses 0 at
   sunrise/sunset. `d` = daylight amount (smoothstep of elev), `tw` = twilight bump peaking at
   elev = 0. Sun and moon travel on arcs from left to right. */
(function (global) {
  "use strict";
  var S = global.SHADERS = {};

  var PRE = [
    "#ifdef GL_FRAGMENT_PRECISION_HIGH",
    "precision highp float;",
    "#else",
    "precision mediump float;",
    "#endif",
    "varying vec2 v_uv;",
    "uniform vec2 u_res;",
    "/* time. The app runs for days, so seconds-since-launch would grow past what fp32 fract() can resolve",
    "   (visible jumps in the cloud and wave drift, structured hash output). The shaders never see a large",
    "   time value: every drift phase k*t is computed in JS in double precision and reduced modulo the",
    "   1024-cell noise period (u_T0..u_T2, see scene.js for the k of each component); because the lattice",
    "   below is periodic in 1024 cells the reduction is seamless. u_tLo = t mod 1024 for the star twinkle,",
    "   u_phase = 1.2*t mod 2pi for the shore sine, u_cloudDrift / u_seaDrift the wind-driven drifts",
    "   integrated in JS, already in lattice units and wrapped. */",
    "uniform float u_tLo, u_phase, u_cloudDrift, u_seaDrift; uniform vec4 u_T0, u_T1; uniform vec2 u_T2;",
    "uniform float u_cloud, u_wind, u_quality;",
    "uniform float u_rain, u_fog, u_flash;",
    "const float PI = 3.14159265;",
    "const float HOR = 0.46;   /* horizon height from the bottom (uv) */",
    "const float SHORE = 0.27; /* shore line height from the bottom */",
    "",
    "/* value noise on a lattice that repeats every 1024 cells: the multipliers are 123/1024 and 456/1024, so for",
    "   integer lattice coordinates fract() is exactly periodic in 1024 (and exact in fp32 below 2^24), which is",
    "   what lets the drift phases be reduced modulo 1024 without a visible wrap. Same cost as the previous hash: the sky pass sits",
    "   right at the frame budget on the Mali-G51 (a heavier hash cost 8 fps). fbm lacunarity is exactly 2, so",
    "   every octave shares the period. */",
    "float hash(vec2 p){ p = fract(p * vec2(0.1201171875, 0.4453125)); p += dot(p, p + 45.32); return fract(p.x * p.y); }",
    "float noise(vec2 p){ vec2 i = floor(p), f = fract(p); f = f*f*(3.0-2.0*f);",
    "  float a = hash(i), b = hash(i+vec2(1,0)), c = hash(i+vec2(0,1)), d = hash(i+vec2(1,1));",
    "  return mix(mix(a,b,f.x), mix(c,d,f.x), f.y); }",
    "float fbm(vec2 p, int oct){ float v = 0.0, a = 0.5; for (int i = 0; i < 5; i++) { if (i >= oct) break; v += a*noise(p); p = p*2.0 + 17.1; a *= 0.5; } return v; }",
    "",
    "/* light state: real astronomy computed in JS (astro.js on SunCalc) and passed as uniforms.",
    "   u_elev = sin(sun altitude); u_sun / u_moon = screen positions in uv (y up); u_moonDir = bright-limb",
    "   direction on screen; u_moonFrac = illuminated fraction; u_moonBright = fraction * visibility. */",
    "uniform float u_elev, u_sunUp, u_moonUp, u_moonFrac, u_moonBright;",
    "uniform vec2 u_sunPos, u_moonPos, u_moonDir;",
    "float g_elev, g_d, g_tw; bool g_isDay; vec2 g_sun, g_moon; vec3 g_sunCol;",
    "/* +-0.5 LSB static dither (R2 quasi-random sequence on the pixel grid, 3 ops): kills the banding of slow",
    "   gradients in the 8-bit sky texture and output, which on a 98-inch panel read as contours that jump */",
    "vec3 dither(vec3 c){ return c + (fract(dot(gl_FragCoord.xy, vec2(0.7548776662, 0.5698402909))) - 0.5) / 255.0; }",
    "void lightState(float asp){",
    "  g_elev = u_elev; g_isDay = u_elev > 0.0;",
    "  g_d = smoothstep(-0.10, 0.28, g_elev);          /* daylight: 0 at civil dusk (-6 deg), 1 well into the day */",
    "  g_tw = exp(-pow(g_elev/0.16, 2.0));             /* twilight bump around the horizon crossing */",
    "  g_sun = vec2(u_sunPos.x*asp, u_sunPos.y); g_moon = vec2(u_moonPos.x*asp, u_moonPos.y);",
    "  g_sunCol = mix(vec3(1.0,0.55,0.25), vec3(1.0,0.95,0.80), g_d);",
    "}",
    ""
  ].join("\n");

  S.SKY = PRE + [
    "void main(){",
    "  vec2 uv = v_uv; float asp = u_res.x / u_res.y; vec2 p = vec2(uv.x*asp, uv.y);",
    "  lightState(asp);",
    "  int oct = u_quality > 1.5 ? 5 : (u_quality > 0.5 ? 3 : 2);",
    "  float d = g_d, tw = g_tw, elev = g_elev;",
    "  /* palette: night / twilight / day, blended by daylight and the twilight bump */",
    "  float h = clamp((uv.y - HOR) / (1.0 - HOR), 0.0, 1.0);",
    "  vec3 top = mix(vec3(0.015,0.025,0.09), vec3(0.14,0.45,0.86), d);",
    "  vec3 hor = mix(vec3(0.05,0.08,0.20), vec3(0.70,0.87,0.98), d);",
    "  top = mix(top, vec3(0.22,0.13,0.42), tw*0.85); hor = mix(hor, vec3(1.0,0.52,0.28), tw);",
    "  vec3 sky = mix(hor, top, pow(h, 0.55));",
    "  /* sun: soft non-saturating glow (mix, not add) + small warm disc */",
    "  float sd = distance(p, g_sun); float sunUp = u_sunUp;",
    "  float glow = 0.55*exp(-sd*11.0) + 0.22*exp(-sd*3.2)*(1.0 + 0.8*tw) + 0.10*exp(-sd*1.2)*tw;",
    "  sky = mix(sky, g_sunCol, clamp(glow, 0.0, 0.85) * sunUp);",
    "  sky = mix(sky, vec3(1.0,0.97,0.88), sunUp * smoothstep(0.030, 0.024, sd) * step(HOR - 0.01, g_sun.y));",
    "  /* stars + Milky Way: only once the sun is really down, washed out by a bright moon */",
    "  float night = smoothstep(0.03, -0.10, elev) * (1.0 - 0.6*u_moonBright);",
    "  if (night > 0.02 && uv.y > HOR) {",
    "    vec2 gp = p * 150.0; vec2 id = floor(gp); float r = hash(id);",
    "    float star = step(0.975, r) * smoothstep(0.35, 0.0, length(fract(gp) - 0.5)) * (0.55 + 0.45*sin(u_tLo*(2.0+r*4.0) + r*90.0));",
    "    sky += vec3(0.9,0.95,1.0) * star * night * 1.3;",
    "    float deep = smoothstep(-0.05, -0.16, elev);   /* the Milky Way band only in full night: at twilight it read as a diagonal seam */",
    "    if (u_quality > 0.5 && deep > 0.01) {",
    "      vec2 rp = vec2(p.x*0.80 + p.y*0.60, -p.x*0.60 + p.y*0.80);",
    "      float band = exp(-pow((rp.y - 0.95)/0.10, 2.0));",
    "      float mw = fbm(rp*vec2(5.0, 11.0) + 3.0, u_quality > 1.5 ? 4 : 3);",
    "      sky += vec3(0.55,0.62,0.85) * band * pow(mw, 2.2) * 0.9 * night * deep;",
    "    }",
    "  }",
    "  /* moon: real position, phase and orientation. The terminator is the ellipse u = -k*sqrt(1-v^2) in",
    "     disc coordinates (u along the bright-limb direction), k = 2*fraction - 1 (-1 new, +1 full). */",
    "  float moonUp = u_moonUp * (1.0 - 0.75*d);          /* fades in daylight (a daytime moon is faint) */",
    "  if (moonUp > 0.0) {",
    "    float R = 0.055; vec2 rel = (p - g_moon) / R; float md = length(rel);",
    "    float mglow = 0.45*exp(-md*R*9.0) + 0.18*exp(-md*R*2.8);",
    "    sky = mix(sky, vec3(0.62,0.70,0.95), clamp(mglow, 0.0, 0.7) * moonUp * (0.25 + 0.75*u_moonFrac));",
    "    if (md < 1.15) {",
    "      vec2 dir = normalize(u_moonDir), perp = vec2(-dir.y, dir.x);",
    "      float u = dot(rel, dir), v = dot(rel, perp), k = 2.0*u_moonFrac - 1.0;",
    "      float disc = smoothstep(1.0, 0.93, md);",
    "      float term = -k * sqrt(max(0.0, 1.0 - v*v));",
    "      float lit = smoothstep(term - 0.06, term + 0.06, u);",
    "      vec3 moonCol = vec3(0.96,0.97,1.0) - 0.08*vec3(noise(p*60.0), noise(p*60.0+3.0), 0.0);   /* faint maria */",
    "      vec3 earthshine = vec3(0.30,0.34,0.48);",
    "      float night = smoothstep(0.03, -0.12, elev);       /* earthshine only shows against a dark sky */",
    "      sky = mix(sky, mix(earthshine, moonCol, lit), disc * moonUp * mix(0.35 * night, 1.0, lit));",
    "    }",
    "  }",
    "  /* clouds: fbm in perspective, drifting with the wind, coverage from the weather */",
    "  if (uv.y > HOR) {",
    "    float hh = max(h, 0.06);",
    "    vec2 cp = vec2((uv.x - 0.5)*asp / hh * 0.55, 0.45 / hh);",
    "    float c = fbm(cp*1.3 + vec2(u_cloudDrift, 0.0), oct);",
    "    float cov = smoothstep(0.62 - u_cloud*0.40, 0.80 - u_cloud*0.15, c) * smoothstep(0.02, 0.18, h);",
    "    vec3 lit = mix(vec3(0.10,0.11,0.18), vec3(1.0,1.0,1.0), d); lit = mix(lit, vec3(1.0,0.70,0.45), tw*0.8);",
    "    vec3 shd = mix(vec3(0.05,0.06,0.12), vec3(0.62,0.70,0.82), d); shd = mix(shd, vec3(0.55,0.30,0.45), tw*0.6);",
    "    vec3 cloudCol = mix(shd, lit, smoothstep(0.55, 0.95, c));",
    "    sky = mix(sky, cloudCol, cov * 0.92);",
    "  }",
    "  /* weather: overcast gloom, fog (denser near the horizon), lightning flash */",
    "  sky = mix(sky, vec3(0.42,0.46,0.55) * mix(0.3, 1.0, d), u_cloud * 0.45 * smoothstep(0.3, 1.0, u_cloud));",
    "  sky = mix(sky, vec3(0.75,0.78,0.84) * mix(0.25, 1.0, d), u_fog * 0.8 * (1.0 - 0.5*h));",
    "  sky += vec3(0.6,0.65,0.8) * u_flash;",
    "  gl_FragColor = vec4(dither(sky), 1.0);",
    "}"
  ].join("\n");

  S.MAIN = PRE + [
    "/* the sky is rendered every N frames into alternating textures; the main pass blends the previous and",
    "   the newest one with u_skyMix ramping over those N frames, so cloud drift and the sunset gradient move",
    "   every frame instead of stepping at 15 Hz */",
    "uniform sampler2D u_sky, u_skyPrev; uniform float u_skyMix;",
    "vec3 skyAt(vec2 uv){ return mix(texture2D(u_skyPrev, uv).rgb, texture2D(u_sky, uv).rgb, u_skyMix); }",
    "void main(){",
    "  vec2 uv = v_uv; float asp = u_res.x / u_res.y; vec2 p = vec2(uv.x*asp, uv.y);",
    "  lightState(asp);",
    "  int oct = u_quality > 0.5 ? 3 : 2;      /* the sea runs every frame: 3 octaves max (the sky keeps 5, refreshed every 4th frame) */",
    "  float d = g_d, tw = g_tw;",
    "  vec3 col;",
    "  if (uv.y > HOR) { col = skyAt(uv); }",
    "  else if (uv.y > SHORE) {",
    "    float depth = (HOR - uv.y) / (HOR - SHORE);        /* 0 horizon .. 1 shore */",
    "    /* wave coordinates: mild perspective (far cells stay larger than a pixel, so no blocky aliasing) */",
    "    float persp = depth + 0.18;",
    "    vec2 wp = vec2((uv.x - 0.5)*asp*3.0 / persp, 4.0 / persp);",
    "    float w = fbm(wp*vec2(1.0, 2.2) + vec2(u_seaDrift, u_T0.x), oct);",
    "    float w2 = noise(wp*vec2(3.0, 9.0) + vec2(-u_T0.y, u_T0.z));                  /* fine ripples */",
    "    vec3 deep = vec3(0.02,0.28,0.46), mid = vec3(0.08,0.66,0.72), shallow = vec3(0.50,0.90,0.86);",
    "    vec3 sea = mix(deep, mid, smoothstep(0.0, 0.55, depth)); sea = mix(sea, shallow, smoothstep(0.55, 1.0, depth));",
    "    sea *= mix(0.22, 1.0, d);",
    "    /* reflection: the real sky just above the horizon, desaturated so twilight does not turn the sea pink */",
    "    vec3 horCol = texture2D(u_sky, vec2(uv.x, HOR + 0.012)).rgb;   /* reflection: the newest sky is enough, no crossfade */",
    "    horCol = mix(horCol, vec3(dot(horCol, vec3(0.33, 0.5, 0.17))), 0.45) * 0.85;",
    "    sea = mix(sea, horCol, pow(1.0 - depth, 3.0) * 0.5);",
    "    sea += (w - 0.5) * (0.08 + 0.06*u_wind*0.05 + 0.08*u_rain) + (w2 - 0.5) * (0.05 + 0.04*u_wind*0.05);   /* wind and rain raise the waves */",
    "    /* light path: a vertical band under the sun/moon, narrow at the horizon, filled with horizontal shimmer streaks */",
    "    /* the sun's path while it is up; otherwise the moon's, as bright as its illuminated fraction */",
    "    bool useSun = u_sunUp > 0.01;",
    "    float lx = useSun ? g_sun.x : g_moon.x;",
    "    float lightOn = useSun ? u_sunUp : u_moonUp * (0.15 + 0.85*u_moonFrac) * (1.0 - 0.6*d);",
    "    vec3 lightCol = useSun ? g_sunCol : vec3(0.80,0.86,1.0);",
    "    float path = exp(-pow((p.x - lx) / (0.035 + 0.22*depth), 2.0)) * lightOn;",
    "    if (path > 0.02) {                                      /* shimmer only inside the light path */",
    "      float streak = noise(vec2(p.x*90.0 + u_T0.w, uv.y*420.0 - u_T1.x)) * noise(vec2(p.x*30.0 - u_T1.y, uv.y*160.0 + u_T1.z));",
    "      float shimmer = smoothstep(0.18, 0.55, streak) * (0.5 + 0.5*w2);",
    "      sea += lightCol * shimmer * path * (0.55 + 1.2*(1.0-d) + 0.9*tw);",
    "    }",
    "    /* foam at a wavy shore line, plus soft streaks of foam washing back */",
    "    float edge = SHORE + 0.018*sin(uv.x*14.0 + u_phase) + 0.010*noise(vec2(uv.x*30.0, u_T1.w));",
    "    float foam = smoothstep(0.030, 0.0, abs(uv.y - edge)) * (0.45 + 0.55*noise(vec2(uv.x*70.0, u_T2.x)));",
    "    foam += smoothstep(0.07, 0.0, uv.y - edge) * 0.22 * smoothstep(0.5, 0.75, noise(vec2(uv.x*40.0 + u_T0.w, uv.y*90.0)));",
    "    sea = mix(sea, vec3(0.96,1.0,1.0) * mix(0.35, 1.0, d), clamp(foam, 0.0, 1.0) * 0.9);",
    "    /* weather on the water: rain speckle, overcast gloom, fog, flash */",
    "    if (u_rain > 0.0) sea += (noise(vec2(p.x*260.0, uv.y*420.0 + u_T2.y)) - 0.5) * 0.28 * u_rain;",
    "    sea = mix(sea, vec3(0.30,0.36,0.42) * mix(0.3, 1.0, d), u_cloud * 0.35 * smoothstep(0.3, 1.0, u_cloud));",
    "    sea = mix(sea, vec3(0.72,0.76,0.82) * mix(0.25, 1.0, d), u_fog * 0.7 * (0.6 + 0.4*(1.0-depth)));",
    "    sea += vec3(0.5,0.55,0.7) * u_flash * 0.6;",
    "    col = sea;",
    "  } else {",
    "    /* sand base (the sprite layer draws the detailed beach on top) */",
    "    float wet = smoothstep(0.0, 0.05, SHORE - uv.y);",
    "    col = mix(vec3(0.78,0.68,0.50), vec3(0.95,0.88,0.70), wet) * mix(0.25, 1.0, d);",
    "    col = mix(col, vec3(0.45,0.48,0.55) * mix(0.3, 1.0, d), u_cloud * 0.3 * smoothstep(0.3, 1.0, u_cloud) + u_fog * 0.4);",
    "  }",
    "  gl_FragColor = vec4(dither(col), 1.0);",
    "}"
  ].join("\n");
})(window);
